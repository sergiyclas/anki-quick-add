"""Generate the HTML frames of the feature tour from the storyboard in video/script.md.

Every demo frame embeds a real screenshot from video/raw (captured by scripts/capture.ts) inside a
"window" on a dark stage, optionally zoomed onto a region of the screenshot. Frame names follow the
storyboard: NNx-name.html -> frames/out/.

Run: python3 video/build/frames/make-frames.py
"""

from __future__ import annotations

import struct
import zlib
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / "out"
RAW = HERE.parents[1] / "raw"
ART = HERE.parents[2] / "art"

REPO_URL = "github.com/sergiyclas/anki-quick-add"


def png_size(path: Path) -> tuple[int, int]:
    with path.open("rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"not a PNG: {path}")
    w, h = struct.unpack(">II", head[16:24])
    return w, h


def icon_svg() -> str:
    return (ART / "icon.svg").read_text(encoding="utf-8")


def page(title: str, body: str, extra_css: str = "") -> str:
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{title}</title>
<link rel="stylesheet" href="../frames.css">
<style>{extra_css}</style></head>
<body>{body}</body></html>"""


def window(image: str, box_w: int, box_h: int, focus: tuple[int, int, int, int] | None = None, title: str = "") -> str:
    """A screenshot inside a browser-like window. `focus` = (x, y, w, h) in source pixels to zoom on."""
    src = RAW / image
    iw, ih = png_size(src)
    if focus:
        fx, fy, fw, fh = focus
    else:
        fx, fy, fw, fh = 0, 0, iw, ih
    scale = min(box_w / fw, box_h / fh)
    # centre the focus region inside the box
    off_x = (box_w - fw * scale) / 2 - fx * scale
    off_y = (box_h - fh * scale) / 2 - fy * scale
    bar = f'<div class="winbar"><span></span><span></span><span></span><em>{title}</em></div>' if title else ""
    return (
        f'<div class="window" style="width:{box_w}px;height:{box_h + (46 if title else 0)}px">{bar}'
        f'<div class="viewport" style="width:{box_w}px;height:{box_h}px">'
        f'<img src="../../../raw/{image}" style="width:{iw * scale:.1f}px;height:{ih * scale:.1f}px;'
        f'transform:translate({off_x:.1f}px,{off_y:.1f}px)"></div></div>'
    )


def demo(name: str, eyebrow: str, title: str, lines: list[str], image: str, *, box=(1040, 700), focus=None, win_title="", note=""):
    bullets = "".join(f"<li>{ln}</li>" for ln in lines)
    note_html = f'<p class="note">{note}</p>' if note else ""
    body = f"""
<div class="stage">
  <div class="copy">
    <div class="eyebrow">{eyebrow}</div>
    <h1>{title}</h1>
    <ul>{bullets}</ul>
    {note_html}
  </div>
  <div class="shot">{window(image, *box, focus=focus, title=win_title)}</div>
</div>"""
    write(name, body)


def write(name: str, body: str, extra_css: str = "") -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.html").write_text(page(name, body, extra_css), encoding="utf-8")
    print(f"frame {name}")


